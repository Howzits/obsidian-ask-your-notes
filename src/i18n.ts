let current: Record<keyof Dict, string> = en;

export function setLanguage(language: "en" | "zh"): void {
	current = language === "zh" ? zh : en;
}

export function t<K extends keyof Dict>(key: K): string {
	return current[key];
}

export function detectLanguage(preference: UILanguage): "en" | "zh" {
	if (preference === "en" || preference === "zh") return preference;
	const lang =
		typeof navigator !== "undefined" ? navigator.language || "en" : "en";
	return lang.toLowerCase().startsWith("zh") ? "zh" : "en";
}
